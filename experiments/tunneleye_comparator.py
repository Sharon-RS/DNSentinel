import json
import csv
from dataclasses import dataclass, asdict
from pathlib import Path
from typing import Dict, Any, Optional, List

from experiments.evaluator import EvaluationMetrics


@dataclass
class TunnelEyeBenchmarkResult:
    """
    Structured container for external TunnelEye reproduction metrics.
    Corresponds to results generated by reproduce_tunneleye.py / classify.py.
    """
    dataset_name: str
    model_name: str
    accuracy: float
    precision: float
    recall: float
    f1_score: float
    false_positive_rate: Optional[float] = None
    false_negative_rate: Optional[float] = None
    source_file: Optional[str] = None
    notes: Optional[str] = None


class TunnelEyeResultIngestor:
    """
    Ingests and parses external TunnelEye reproduction artifacts
    (all_results.json, paper_vs_reproduction.csv, etc.) without
    re-running or modifying the TunnelEye reproduction pipeline.
    """

    @staticmethod
    def load_json_results(json_path: str) -> Dict[str, Any]:
        """
        Loads all_results.json from the external reproduction run.
        """
        path = Path(json_path)
        if not path.exists():
            raise FileNotFoundError(f"TunnelEye result file not found: {path}")

        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)

    @staticmethod
    def load_csv_summary(csv_path: str) -> List[Dict[str, str]]:
        """
        Loads paper_vs_reproduction.csv from the external reproduction run.
        """
        path = Path(csv_path)
        if not path.exists():
            raise FileNotFoundError(f"TunnelEye CSV summary not found: {path}")

        records = []
        with open(path, "r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                records.append(dict(row))
        return records


class BenchmarkComparator:
    """
    Produces side-by-side comparative summaries between DNSentinel's
    empirical evaluation results and external TunnelEye baseline results.
    Strictly preserves provenance without metric fabrication.
    """

    @staticmethod
    def format_comparison_table(
        dnsentinel_metrics: EvaluationMetrics,
        tunneleye_result: TunnelEyeBenchmarkResult
    ) -> str:
        """
        Formats a clean, side-by-side comparison table.
        """
        lines = [
            "=" * 78,
            " RESEARCH BENCHMARK COMPARISON: DNSentinel vs. TunnelEye Baseline",
            "=" * 78,
            f"{'Metric':<25} | {'DNSentinel (Adaptive)':<24} | {'TunnelEye (Baseline)':<24}",
            "-" * 78,
            f"{'Model / Architecture':<25} | {'3-Tier Behavioral':<24} | {tunneleye_result.model_name:<24}",
            f"{'Dataset / Context':<25} | {'Evaluated Event Stream':<24} | {tunneleye_result.dataset_name:<24}",
            f"{'Accuracy':<25} | {dnsentinel_metrics.accuracy:<24.4f} | {tunneleye_result.accuracy:<24.4f}",
            f"{'Precision (Weighted)':<25} | {dnsentinel_metrics.precision:<24.4f} | {tunneleye_result.precision:<24.4f}",
            f"{'Recall / Detection Rate':<25} | {dnsentinel_metrics.recall:<24.4f} | {tunneleye_result.recall:<24.4f}",
            f"{'F1-Score':<25} | {dnsentinel_metrics.f1_score:<24.4f} | {tunneleye_result.f1_score:<24.4f}",
        ]

        if tunneleye_result.false_positive_rate is not None:
            lines.append(
                f"{'False Positive Rate':<25} | {dnsentinel_metrics.false_positive_rate:<24.4f} | {tunneleye_result.false_positive_rate:<24.4f}"
            )

        if tunneleye_result.false_negative_rate is not None:
            lines.append(
                f"{'False Negative Rate':<25} | {dnsentinel_metrics.false_negative_rate:<24.4f} | {tunneleye_result.false_negative_rate:<24.4f}"
            )

        lines.extend([
            f"{'Contamination Protected':<25} | {'YES (Guarded)':<24} | {'N/A (Batch Classifier)':<24}",
            f"{'Adaptive Host Memory':<25} | {'YES (Dynamic)':<24} | {'NO (Static Features)':<24}",
            "=" * 78,
        ])

        return "\n".join(lines)
